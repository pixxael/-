const rand = (min, max) => Math.floor(Math.random() * (max - min + 1)) + min;
const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
const uniquePick = (arr, exclude = []) => pick(arr.filter(i => !exclude.includes(i.n)));

// 🔄 ГЕНЕРАТОР (200+ рецептов с точными шагами и КБЖУ)
function generateRecipes() {
  const generated = [];
  let idCounter = 100;

  for (let i = 0; i < 200; i++) {
    const protein = pick(baseIngredients.filter(i => i.p > 10 && !['яйца','сыр','творог'].includes(i.n)));
    const carb = uniquePick(baseIngredients.filter(i => i.c > 10 && i.k > 80), [protein]);
    const veg1 = uniquePick(baseIngredients.filter(i => i.k < 40), [protein, carb]);
    const veg2 = uniquePick(baseIngredients.filter(i => i.k < 40), [protein, carb, veg1]);
    
    const methodType = pick(['fry', 'bake', 'simmer']);
    const oil = pick(baseIngredients.filter(i => i.n.includes('масло')));
    
    // Расчёт КБЖУ под точные граммовки
    const pAmt = rand(120, 180);
    const cAmt = rand(60, 120);
    const v1Amt = rand(50, 100);
    const v2Amt = rand(40, 80);
    const oilAmt = rand(5, 15);

    const totalK = Math.round((protein.k * pAmt/100) + (carb.k * cAmt/100) + (veg1.k * v1Amt/100) + (veg2.k * v2Amt/100) + (oil.k * oilAmt/100));
    const totalP = Math.round((protein.p * pAmt/100) + (carb.p * cAmt/100) + (veg1.p * v1Amt/100) + (veg2.p * v2Amt/100) + (oil.p * oilAmt/100));
    const totalF = Math.round((protein.f * pAmt/100) + (carb.f * cAmt/100) + (veg1.f * v1Amt/100) + (veg2.f * v2Amt/100) + (oil.f * oilAmt/100));
    const totalC = Math.round((protein.c * pAmt/100) + (carb.c * cAmt/100) + (veg1.c * v1Amt/100) + (veg2.c * v2Amt/100) + (oil.c * oilAmt/100));

    const ingredients = [
      {n: protein.n, a: `${pAmt} г`},
      {n: carb.n, a: `${cAmt} г`},
      {n: veg1.n, a: `${v1Amt} г`},
      {n: veg2.n, a: `${v2Amt} г`},
      {n: oil.n, a: `${oilAmt} г`},
      {n: "соль", a: "0.5 ч.л."},
      {n: "перец чёрный", a: "по вкусу"}
    ];

    // Формируем точные шаги
    let steps = [];
    steps.push(stepTemplates.prep(protein.n));
    steps.push(stepTemplates.prep(`${carb.n} (отварите отдельно до полуготовности за ${rand(8,15)} мин)`));
    steps.push(stepTemplates.heat(`${oilAmt} г ${oil.n}`));
    
    if (methodType === 'fry') {
      steps.push(stepTemplates.protein(protein.n, `${rand(5,8)} мин`));
      steps.push(stepTemplates.veg(veg1.n, veg2.n, `${rand(4,6)} мин`));
    } else if (methodType === 'simmer') {
      steps.push(stepTemplates.protein(protein.n, `${rand(4,6)} мин`));
      steps.push(stepTemplates.veg(veg1.n, veg2.n, `${rand(3,5)} мин`));
      steps.push(stepTemplates.liquid("100 мл воды или бульона", `${rand(10,15)} мин`));
    } else {
      steps.push(stepTemplates.protein(protein.n, `${rand(4,6)} мин`));
      steps.push(stepTemplates.veg(veg1.n, veg2.n, `${rand(3,5)} мин`));
      steps.push(stepTemplates.bake(`${rand(20,30)}`));
    }
    steps.push(stepTemplates.finish);

    generated.push({
      id: idCounter++,
      title: `${methodType === 'fry' ? 'Жареное' : methodType === 'bake' ? 'Запечённое' : 'Тушёное'} ${protein.n} с ${carb.n}`,
      ingredients: ingredients,
      time: `${rand(25, 50)} мин`,
      kbzhu: { c: totalK, p: totalP, f: totalF, k: totalC },
      steps: steps
    });
  }
  return generated;
}

